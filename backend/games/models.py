# 7. ACTIVITY FEED
# ============================================
class ActivityFeed(models.Model):
    """
    Recent puzzle completions by all users.
    Limited to last 50 events.
    """
    EVENT_TYPES = [
        ('puzzle_completed', 'Puzzle Completed'),
        ('streak_milestone', 'Streak Milestone'),
        ('leaderboard_top', 'Leaderboard Top 3'),
    ]
    
    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name='activities')
    event_type = models.CharField(max_length=30, choices=EVENT_TYPES)
    
    # Event details
    puzzle_type = models.CharField(max_length=20, blank=True, null=True)
    points = models.IntegerField(default=0)
    tries = models.IntegerField(null=True, blank=True)
    
    # Additional metadata (JSON for flexibility)
    metadata = models.JSONField(default=dict, blank=True)
    
    # Timestamp
    created_at = models.DateTimeField(auto_now_add=True, db_index=True)
    
    class Meta:
        db_table = 'activity_feed'
        indexes = [
            models.Index(fields=['-created_at']),
            models.Index(fields=['event_type', '-created_at']),
        ]
        ordering = ['-created_at']
    
    def __str__(self):
        return f"{self.user.username} - {self.event_type} - {self.created_at}"


