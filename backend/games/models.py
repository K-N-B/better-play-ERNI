from django.db import models
from django.contrib.auth import get_user_model
from django.core.validators import MinValueValidator
from django.utils import timezone

User = get_user_model()


# ============================================
# 1. PUZZLES TABLE
# ============================================
class Puzzle(models.Model):
    """
    Stores daily puzzles generated by Gemini AI.
    Two records per game type per day (Easy + Hard).
    """
    PUZZLE_TYPES = [
        ('wordle', 'Wordle'),
        ('sudoku', 'Sudoku'),
        ('ernigram', 'ERNIgram'),
    ]
    
    DIFFICULTY_CHOICES = [
        ('easy', 'Easy'),
        ('hard', 'Hard'),
    ]
    
    puzzle_type = models.CharField(max_length=20, choices=PUZZLE_TYPES)
    difficulty = models.CharField(max_length=10, choices=DIFFICULTY_CHOICES)
    puzzle_date = models.DateField(db_index=True)
    
    # Wordle-specific fields
    solution_word = models.CharField(max_length=10, blank=True, null=True)
    
    # Sudoku-specific fields
    puzzle_string = models.TextField(blank=True, null=True)
    solution_string = models.TextField(blank=True, null=True)
    
    # ERNIgram-specific fields
    solution_phrase = models.CharField(max_length=255, blank=True, null=True)
    clue = models.TextField(blank=True, null=True)
    
    # AI-generated hints (stored as JSON)
    hints = models.JSONField(default=dict, blank=True)
    # Example: {"hint_1": "...", "hint_2": "...", "hint_3": "..."}
    
    # Metadata
    is_active = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)
    
    class Meta:
        db_table = 'puzzles'
        unique_together = ['puzzle_type', 'difficulty', 'puzzle_date']
        indexes = [
            models.Index(fields=['puzzle_date', 'puzzle_type', 'difficulty']),
            models.Index(fields=['is_active', 'puzzle_date']),
        ]
        ordering = ['-puzzle_date', 'puzzle_type']
    
    def __str__(self):
        return f"{self.puzzle_type.title()} - {self.difficulty.title()} - {self.puzzle_date}"


# ============================================
# 2. USER PROGRESS TABLE (Auto-save)
# ============================================
class UserProgress(models.Model):
    """
    Stores in-progress game states (auto-saved every 2 seconds).
    Cleared when puzzle is submitted.
    """
    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name='progress')
    puzzle = models.ForeignKey(Puzzle, on_delete=models.CASCADE)
    puzzle_type = models.CharField(max_length=20)  # Denormalized for faster queries
    
    # Game state stored as JSON
    progress_data = models.JSONField(default=dict)
    # Example for Wordle: {"guesses": ["HOUSE"], "currentRow": 1, ...}
    
    # Timer tracking
    time_spent_ms = models.IntegerField(default=0, validators=[MinValueValidator(0)])
    
    # Timestamps
    last_saved = models.DateTimeField(auto_now=True)
    created_at = models.DateTimeField(auto_now_add=True)
    
    class Meta:
        db_table = 'user_progress'
        unique_together = ['user', 'puzzle']
        indexes = [
            models.Index(fields=['user', 'puzzle_type']),
            models.Index(fields=['last_saved']),
        ]
    
    def __str__(self):
        return f"{self.user.username} - {self.puzzle_type} - {self.puzzle.puzzle_date}"


# ============================================
# 3. SUBMISSIONS TABLE (Completed Puzzles)
# ============================================
class Submission(models.Model):
    """
    Final submissions when user completes a puzzle.
    One submission per user per puzzle.
    """
    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name='submissions')
    puzzle = models.ForeignKey(Puzzle, on_delete=models.CASCADE, related_name='submissions')
    puzzle_type = models.CharField(max_length=20)  # Denormalized
    
    # Performance metrics
    tries = models.IntegerField(validators=[MinValueValidator(1)])
    time_taken_ms = models.IntegerField(validators=[MinValueValidator(0)])
    points_awarded = models.IntegerField(default=0)
    
    # Timestamp
    created_at = models.DateTimeField(auto_now_add=True, db_index=True)
    
    class Meta:
        db_table = 'submissions'
        unique_together = ['user', 'puzzle']
        indexes = [
            models.Index(fields=['user', 'created_at']),
            models.Index(fields=['puzzle_type', 'created_at']),
            models.Index(fields=['-points_awarded']),
        ]
        ordering = ['-created_at']
    
    def __str__(self):
        return f"{self.user.username} - {self.puzzle_type} - {self.points_awarded}pts"


