# 4. DAILY COMPLETION STATUS
# ============================================
class DailyCompletionStatus(models.Model):
    """
    Tracks how many puzzles user completed each day.
    Used for streak calculation.
    """
    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name='daily_status')
    completion_date = models.DateField(db_index=True)
    
    # Track individual puzzle completions
    wordle_completed = models.BooleanField(default=False)
    sudoku_completed = models.BooleanField(default=False)
    ernigram_completed = models.BooleanField(default=False)
    
    # Total count (0-3)
    puzzles_completed_count = models.IntegerField(default=0, validators=[MinValueValidator(0)])
    
    # Points earned today
    points_earned_today = models.IntegerField(default=0)
    
    class Meta:
        db_table = 'daily_completion_status'
        unique_together = ['user', 'completion_date']
        indexes = [
            models.Index(fields=['user', 'completion_date']),
            models.Index(fields=['completion_date']),
        ]
        ordering = ['-completion_date']
    
    def __str__(self):
        return f"{self.user.username} - {self.completion_date} - {self.puzzles_completed_count}/3"
    
    def is_all_completed(self):
        """Check if user completed all 3 puzzles"""
        return self.puzzles_completed_count == 3


