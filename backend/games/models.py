# 5. STREAKS TABLE
# ============================================
class Streak(models.Model):
    """
    Tracks user's consecutive days of completing ALL puzzles.
    """
    user = models.OneToOneField(User, on_delete=models.CASCADE, related_name='streak')
    
    current_streak_count = models.IntegerField(default=0, validators=[MinValueValidator(0)])
    max_streak_count = models.IntegerField(default=0, validators=[MinValueValidator(0)])
    
    last_completion_date = models.DateField(null=True, blank=True)
    
    # Metadata
    updated_at = models.DateTimeField(auto_now=True)
    
    class Meta:
        db_table = 'streaks'
    
    def __str__(self):
        return f"{self.user.username} - Current: {self.current_streak_count}, Max: {self.max_streak_count}"


