# 6. LEADERBOARD CACHE
# ============================================
class LeaderboardCache(models.Model):
    """
    Pre-calculated leaderboard rankings for performance.
    Regenerated periodically.
    """
    PERIOD_CHOICES = [
        ('daily', 'Daily'),
        ('weekly', 'Weekly'),
        ('monthly', 'Monthly'),
        ('alltime', 'All-Time'),
    ]
    
    period = models.CharField(max_length=20, choices=PERIOD_CHOICES, db_index=True)
    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name='leaderboard_entries')
    
    rank = models.IntegerField(validators=[MinValueValidator(1)])
    score = models.IntegerField(default=0)
    
    # For tracking rank changes
    previous_rank = models.IntegerField(null=True, blank=True)
    
    # Timestamp of calculation
    calculated_at = models.DateTimeField(auto_now=True)
    
    class Meta:
        db_table = 'leaderboard_cache'
        unique_together = ['period', 'user']
        indexes = [
            models.Index(fields=['period', 'rank']),
            models.Index(fields=['period', '-score']),
        ]
        ordering = ['period', 'rank']
    
    def __str__(self):
        return f"{self.period} - Rank {self.rank}: {self.user.username} ({self.score}pts)"


